# Loop kya hota hai?
# Loop ka matlab hai ek kaam ko baar-baar repeat karwana, 
# jab tak condition true hai.
# Python me mainly do tarah ke loops hote hain -> for loop aur while loop.
# Hum sequences (list, tuple, range, string) pe loop chala sakte hain.

# Example ke liye, ek range produce kaise hoti hai:
# range(start, stop) -> stop value exclusive hoti hai (include nahi hoti)
# Yani range(1, 5) => 1, 2, 3, 4

# Yeh sirf explainatory example hai
for number in range(1, 6):  # 1 se lekar 5 tak loop chalega
    print("Number:", number)  # Current number print hoga

