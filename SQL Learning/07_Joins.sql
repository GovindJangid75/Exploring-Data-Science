-- INNER JOIN -> matching rows

SELECT S.NAME, S.MARKS, D.DEPT_NAME
FROM STUDENT S
INNER JOIN DEPARTMENT D
ON S.DEPT_ID = D.ID;


-- LEFT JOIN -> left ki saari rows

SELECT *
FROM STUDENT S
LEFT JOIN DEPARTMENT D
ON S.DEPT_ID = D.ID;


-- RIGHT JOIN -> right ki saari rows

SELECT *
FROM STUDENT S
RIGHT JOIN DEPARTMENT D
ON S.DEPT_ID = D.ID;


-- MySQL me direct FULL OUTER JOIN nahi hota
-- LEFT + RIGHT ko UNION kar sakte hain

SELECT *
FROM STUDENT S
LEFT JOIN DEPARTMENT D
ON S.DEPT_ID = D.ID

UNION

SELECT *
FROM STUDENT S
RIGHT JOIN DEPARTMENT D
ON S.DEPT_ID = D.ID;


-- CROSS JOIN -> har row ka har row se combination
-- like cross in sets
SELECT S.NAME, D.DEPT_NAME
FROM STUDENT S
CROSS JOIN DEPARTMENT D;


