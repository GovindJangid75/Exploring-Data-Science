
-- Lecture 07 - SQL JOINs


CREATE DATABASE IF NOT EXISTS COLLEGE_DB;
USE COLLEGE_DB;


CREATE TABLE DEPARTMENT (
    ID INT PRIMARY KEY,
    DEPT_NAME VARCHAR(50),
    DEPT_HEAD VARCHAR(50)
);

CREATE TABLE STUDENT (
    ID INT PRIMARY KEY,
    NAME VARCHAR(50),
    EMAIL VARCHAR(100),
    CITY VARCHAR(30),
    MARKS INT,
    DEPT_ID INT,
    FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT(ID)
);


