
-- Lecture 05 - Aggregate Functions & Subqueries


USE STUDENTSSS;


-- Aggregate Functions

SELECT AVG(CGPA) AS AVG_CGPA
FROM STUDENTS;

SELECT MAX(CGPA) AS HIGHEST_CGPA
FROM STUDENTS;

SELECT MIN(CGPA) AS LOWEST_CGPA
FROM STUDENTS;

SELECT COUNT(*) AS TOTAL_STUDENTS
FROM STUDENTS;

SELECT SUM(CGPA) AS TOTAL_CGPA
FROM STUDENTS;


-- COUNT(column) NULL values leta hi nhi hai
-- COUNT(*) total rows count karta hai


-- Subquery
-- Highest CGPA wala student

SELECT *
FROM STUDENTS
WHERE CGPA = (
    SELECT MAX(CGPA)
    FROM STUDENTS
);


-- INSERT INTO SELECT

CREATE TABLE ITSTD LIKE STUDENTS;

INSERT INTO ITSTD
SELECT *
FROM STUDENTS
WHERE CGPA < 8.5;

SELECT * FROM ITSTD;


-- Even / Odd ID example

